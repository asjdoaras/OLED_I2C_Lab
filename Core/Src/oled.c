/* framebuffer: 8 pages x 128 columns */
static uint8_t FB[8][128];

/* Send a command byte */
void OLED_Write_Cmd(uint8_t cmd)
{
  uint8_t buf[2];
  buf[0] = 0x00;
  buf[1] = cmd;
  HAL_I2C_Master_Transmit(&hi2c1, OLED_ADDR, buf, 2, 100);
}

/* Send a data (display RAM) byte */
void OLED_Write_Data(uint8_t data)
{
  uint8_t buf[2];
  buf[0] = 0x40;
  buf[1] = data;
  HAL_I2C_Master_Transmit(&hi2c1, OLED_ADDR, buf, 2, 100);
}

/* Set cursor: x 0..127, page 0..7 (one page = 8 pixel rows) */
void OLED_Set_Pos(uint8_t x, uint8_t page)
{
  OLED_Write_Cmd(0xb0 + page);
  OLED_Write_Cmd(((x & 0xf0) >> 4) | 0x10);
  OLED_Write_Cmd(x & 0x0f);
}

/* Clear the whole screen */
void OLED_Clear(void)
{
  uint8_t page, i;
  for (page = 0; page < 8; page++)
  {
    OLED_Set_Pos(0, page);
    for (i = 0; i < 128; i++)
    {
      OLED_Write_Data(0x00);
    }
  }
}

/* SSD1306 init sequence */
void OLED_Init(void)
{
  OLED_AddrDetect();
  HAL_Delay(100);
  OLED_Write_Cmd(0xAE); /* display off */
  OLED_Write_Cmd(0xD5);
  OLED_Write_Cmd(0x80);
  OLED_Write_Cmd(0xA8);
  OLED_Write_Cmd(0x3F);
  OLED_Write_Cmd(0xD3);
  OLED_Write_Cmd(0x00);
  OLED_Write_Cmd(0x40);
  OLED_Write_Cmd(0x8D);
  OLED_Write_Cmd(0x14);
  OLED_Write_Cmd(0x20);
  OLED_Write_Cmd(0x02);
  OLED_Write_Cmd(0xA1);
  OLED_Write_Cmd(0xC8);
  OLED_Write_Cmd(0xDA);
  OLED_Write_Cmd(0x12);
  OLED_Write_Cmd(0x81);
  OLED_Write_Cmd(0xCF);
  OLED_Write_Cmd(0xD9);
  OLED_Write_Cmd(0xF1);
  OLED_Write_Cmd(0xDB);
  OLED_Write_Cmd(0x30);
  OLED_Write_Cmd(0xA4);
  OLED_Write_Cmd(0xA6);
  OLED_Write_Cmd(0xAF); /* display on */
  OLED_Clear();
}

/* Show one 8x16 character directly on screen */
void OLED_ShowChar(uint8_t x, uint8_t page, uint8_t ch)
{
  uint8_t i, idx;
  if (ch < 0x20 || ch > 0x7E)
  {
    ch = ' ';
  }
  idx = ch - 0x20;
  OLED_Set_Pos(x, page);
  for (i = 0; i < 8; i++)
  {
    OLED_Write_Data(F8X16[idx][i]);
  }
  OLED_Set_Pos(x, page + 1);
  for (i = 0; i < 8; i++)
  {
    OLED_Write_Data(F8X16[idx][i + 8]);
  }
}

/* Show a string directly on screen */
void OLED_ShowString(uint8_t x, uint8_t page, const char *str)
{
  while (*str)
  {
    if (x > 120)
    {
      x = 0;
      page += 2;
    }
    if (page > 7)
    {
      page = 0;
      x = 0;
      OLED_Clear();
    }
    OLED_ShowChar(x, page, (uint8_t)*str);
    x += 8;
    str++;
  }
}

/* Show an unsigned number with fixed length */
void OLED_ShowNum(uint8_t x, uint8_t page, uint32_t num, uint8_t len)
{
  uint8_t t;
  uint32_t fac = 1;
  uint8_t enshow = 0;
  for (t = 1; t < len; t++)
  {
    fac *= 10;
  }
  for (t = 0; t < len; t++)
  {
    uint8_t temp = (uint8_t)((num / fac) % 10);
    if (enshow == 0 && t < (len - 1))
    {
      if (temp == 0)
      {
        OLED_ShowChar(x + 8 * t, page, ' ');
        fac /= 10;
        continue;
      }
      enshow = 1;
    }
    OLED_ShowChar(x + 8 * t, page, temp + '0');
    fac /= 10;
  }
}

/* Show one 16x16 Chinese character directly on screen */
void OLED_ShowChinese(uint8_t x, uint8_t page, const uint8_t *ch)
{
  uint8_t i;
  OLED_Set_Pos(x, page);
  for (i = 0; i < 16; i++)
  {
    OLED_Write_Data(ch[i]);
  }
  OLED_Set_Pos(x, page + 1);
  for (i = 0; i < 16; i++)
  {
    OLED_Write_Data(ch[i + 16]);
  }
}

/* ---------------- framebuffer layer ---------------- */

void OLED_FB_Clear(void)
{
  uint8_t p, x;
  for (p = 0; p < 8; p++)
  {
    for (x = 0; x < 128; x++)
    {
      FB[p][x] = 0;
    }
  }
}

/* Draw one 8x16 ASCII glyph into FB (page = top page, occupies page/page+1) */
void OLED_FB_DrawChar(uint8_t x, uint8_t page, uint8_t ch)
{
  uint8_t i, idx;
  if (ch < 0x20 || ch > 0x7E)
  {
    return;
  }
  idx = ch - 0x20;
  for (i = 0; i < 8; i++)
  {
    if (x + i < 128)
    {
      FB[page][x + i]     |= F8X16[idx][i];
      FB[page + 1][x + i] |= F8X16[idx][i + 8];
    }
  }
}

/* Draw a string into FB */
void OLED_FB_ShowString(uint8_t x, uint8_t page, const char *str)
{
  while (*str)
  {
    OLED_FB_DrawChar(x, page, (uint8_t)*str);
    x += 8;
    str++;
  }
}

/* Draw one 16x16 Chinese glyph into FB */
void OLED_FB_DrawChinese(uint8_t x, uint8_t page, const uint8_t *ch)
{
  uint8_t i;
  for (i = 0; i < 16; i++)
  {
    if (x + i < 128)
    {
      FB[page][x + i]     |= ch[i];
      FB[page + 1][x + i] |= ch[i + 16];
    }
  }
}

/* Hardware-style bulk refresh: horizontal addressing, one I2C burst per page */
void OLED_Flip(void)
{
  uint8_t p, x;
  uint8_t tx[129];
  OLED_Write_Cmd(0x20);
  OLED_Write_Cmd(0x00); /* horizontal addressing */
  for (p = 0; p < 8; p++)
  {
    OLED_Set_Pos(0, p);
    tx[0] = 0x40;
    for (x = 0; x < 128; x++)
    {
      tx[1 + x] = FB[p][x];
    }
    HAL_I2C_Master_Transmit(&hi2c1, OLED_ADDR, tx, 129, 200);
  }
}

/*
 * Render the scroll sequence into FB at `page`, window shifted by `offset` px.
 * Returns total pixel width of the sequence.
 */
uint16_t OLED_ScrollRender(const OLED_Glyph *seq, uint16_t n, uint8_t page, uint16_t offset)
{
  uint16_t i, sx = 0;
  for (i = 0; i < n; i++)
  {
    uint16_t w = (seq[i].type == 0) ? 8 : 16;
    int16_t dx = (int16_t)(sx - offset);
    if (dx >= 0 && dx < 128)
    {
      if (seq[i].type == 0)
      {
        OLED_FB_DrawChar((uint8_t)dx, page, seq[i].code);
      }
      else
      {
        OLED_FB_DrawChinese((uint8_t)dx, page, seq[i].han);
      }
    }
    sx += w;
  }
  return sx;
}
