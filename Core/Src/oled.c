/* I2C slave address: auto-detected between 0x78 and 0x7A */
static uint8_t OLED_ADDR = 0x78;

/* Try both slave addresses and keep the one that answers */
static void OLED_AddrDetect(void)
{
  if (HAL_I2C_IsDeviceReady(&hi2c1, 0x78, 1, 50) == HAL_OK)
  {
    OLED_ADDR = 0x78;
  }
  else if (HAL_I2C_IsDeviceReady(&hi2c1, 0x7A, 1, 50) == HAL_OK)
  {
    OLED_ADDR = 0x7A;
  }
}

